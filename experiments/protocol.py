"""Formal SCRP split, seed, and result schemas.

Static-instance assignment is the unit of splitting. Scenario seeds are kept
out of the split manifest and generated by a separate deterministic schedule.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import asdict, dataclass, fields
from pathlib import Path
from typing import Any, Dict, Iterable, Mapping, Sequence, Tuple


SPLIT_NAMES = ("train", "validation", "test")
SPLIT_PROTOCOL_VERSION = "scrp-static-split-v1"
DEFAULT_DATASET_VERSION = "ku-galle-bacci-ds1-ds2-ec672df"
_KU_FILENAME = re.compile(
    r"^(T(?P<date>271014|281014)_(?P<stacks>\d{2})(?P<tiers>\d{2})_"
    r"(?P<index>\d{3}))\.txt$"
)


class ProtocolValidationError(ValueError):
    """Raised when a split, schedule, config, or result is inconsistent."""


@dataclass(frozen=True)
class SplitCounts:
    train: int = 20
    validation: int = 5
    test: int = 5

    def __post_init__(self) -> None:
        values = (self.train, self.validation, self.test)
        if any(isinstance(value, bool) or not isinstance(value, int) or value <= 0 for value in values):
            raise ProtocolValidationError("all split counts must be positive integers")

    @property
    def total(self) -> int:
        return self.train + self.validation + self.test


@dataclass(frozen=True, order=True)
class BaseInstanceRef:
    base_instance_id: str
    original_instance_id: str
    ds1_instance_id: str
    ds2_instance_id: str
    parameter_group: str

    def __post_init__(self) -> None:
        if any(not value for value in asdict(self).values()):
            raise ProtocolValidationError("base-instance reference fields must be non-empty")
        if self.base_instance_id != self.original_instance_id:
            raise ProtocolValidationError(
                "base_instance_id must be the original Ku instance ID"
            )
        if self.ds1_instance_id != f"ku2016-{self.original_instance_id}":
            raise ProtocolValidationError("DS1 converted ID does not match the Phase 3 rule")
        if self.ds2_instance_id != f"{self.ds1_instance_id}-merge2":
            raise ProtocolValidationError("DS2 derived ID does not match the Phase 3 rule")

    def to_record(self) -> Dict[str, str]:
        return asdict(self)

    @classmethod
    def from_record(cls, record: Mapping[str, Any]) -> "BaseInstanceRef":
        expected = {
            "base_instance_id",
            "original_instance_id",
            "ds1_instance_id",
            "ds2_instance_id",
            "parameter_group",
        }
        if set(record) != expected:
            raise ProtocolValidationError("base-instance reference keys mismatch")
        return cls(**{key: str(record[key]) for key in expected})


@dataclass(frozen=True)
class SplitManifest:
    protocol_version: str
    dataset_version: str
    split_seed: int
    split_counts: SplitCounts
    groups: Mapping[str, Mapping[str, Tuple[BaseInstanceRef, ...]]]

    def __post_init__(self) -> None:
        if self.protocol_version != SPLIT_PROTOCOL_VERSION:
            raise ProtocolValidationError(
                f"unsupported split protocol version {self.protocol_version!r}"
            )
        if not self.dataset_version:
            raise ProtocolValidationError("dataset_version must be non-empty")
        if isinstance(self.split_seed, bool) or not isinstance(self.split_seed, int):
            raise ProtocolValidationError("split_seed must be an integer")
        normalized: Dict[str, Dict[str, Tuple[BaseInstanceRef, ...]]] = {}
        all_base_ids = set()
        all_ds1_ids = set()
        all_ds2_ids = set()
        expected_counts = {
            "train": self.split_counts.train,
            "validation": self.split_counts.validation,
            "test": self.split_counts.test,
        }
        for group, assignments in sorted(self.groups.items()):
            if set(assignments) != set(SPLIT_NAMES):
                raise ProtocolValidationError(f"group {group} must contain all three splits")
            normalized[group] = {}
            group_base_ids = set()
            for split in SPLIT_NAMES:
                refs = tuple(assignments[split])
                if len(refs) != expected_counts[split]:
                    raise ProtocolValidationError(
                        f"group {group}/{split} expected {expected_counts[split]} refs, got {len(refs)}"
                    )
                for ref in refs:
                    if ref.parameter_group != group:
                        raise ProtocolValidationError(
                            f"reference {ref.base_instance_id} has wrong parameter group"
                        )
                    if ref.base_instance_id in group_base_ids:
                        raise ProtocolValidationError(
                            f"base instance {ref.base_instance_id} overlaps splits"
                        )
                    group_base_ids.add(ref.base_instance_id)
                    if ref.base_instance_id in all_base_ids:
                        raise ProtocolValidationError(
                            f"base instance {ref.base_instance_id} appears in multiple groups"
                        )
                    if ref.ds1_instance_id in all_ds1_ids or ref.ds2_instance_id in all_ds2_ids:
                        raise ProtocolValidationError("derived instance ID appears more than once")
                    all_base_ids.add(ref.base_instance_id)
                    all_ds1_ids.add(ref.ds1_instance_id)
                    all_ds2_ids.add(ref.ds2_instance_id)
                normalized[group][split] = refs
            if len(group_base_ids) != self.split_counts.total:
                raise ProtocolValidationError(f"group {group} does not partition its instances")
        object.__setattr__(self, "groups", normalized)

    @property
    def num_groups(self) -> int:
        return len(self.groups)

    @property
    def num_base_instances(self) -> int:
        return sum(
            len(refs)
            for assignments in self.groups.values()
            for refs in assignments.values()
        )

    def refs(self, split: str | None = None) -> Tuple[BaseInstanceRef, ...]:
        if split is not None and split not in SPLIT_NAMES:
            raise ProtocolValidationError(f"unknown split {split!r}")
        return tuple(
            ref
            for group in sorted(self.groups)
            for split_name in SPLIT_NAMES
            if split is None or split_name == split
            for ref in self.groups[group][split_name]
        )

    def split_for_base(self, base_instance_id: str) -> str:
        found = [
            split
            for assignments in self.groups.values()
            for split in SPLIT_NAMES
            if any(ref.base_instance_id == base_instance_id for ref in assignments[split])
        ]
        if len(found) != 1:
            raise ProtocolValidationError(
                f"base instance {base_instance_id!r} has {len(found)} split assignments"
            )
        return found[0]

    def to_record(self) -> Dict[str, Any]:
        return {
            "protocol_version": self.protocol_version,
            "dataset_version": self.dataset_version,
            "split_seed": self.split_seed,
            "split_counts": asdict(self.split_counts),
            "groups": {
                group: {
                    split: [ref.to_record() for ref in assignments[split]]
                    for split in SPLIT_NAMES
                }
                for group, assignments in sorted(self.groups.items())
            },
        }

    @classmethod
    def from_record(cls, record: Mapping[str, Any]) -> "SplitManifest":
        expected = {
            "protocol_version", "dataset_version", "split_seed", "split_counts", "groups"
        }
        if set(record) != expected:
            raise ProtocolValidationError("split manifest keys mismatch")
        counts = SplitCounts(**record["split_counts"])
        groups = {
            str(group): {
                split: tuple(BaseInstanceRef.from_record(item) for item in assignments[split])
                for split in SPLIT_NAMES
            }
            for group, assignments in record["groups"].items()
        }
        return cls(
            protocol_version=str(record["protocol_version"]),
            dataset_version=str(record["dataset_version"]),
            split_seed=int(record["split_seed"]),
            split_counts=counts,
            groups=groups,
        )


def _parameter_group(num_stacks: int, max_tiers: int, fill_rate: float) -> str:
    return f"S{num_stacks:02d}_T{max_tiers:02d}_mu{fill_rate:.2f}"


def _ref_from_source_filename(filename: str, header: Sequence[str] | None = None) -> BaseInstanceRef:
    match = _KU_FILENAME.fullmatch(filename)
    if not match:
        raise ProtocolValidationError(f"unsupported Ku source filename {filename!r}")
    original_id = match.group(1)
    num_stacks = int(match.group("stacks"))
    max_tiers = int(match.group("tiers"))
    fill_rate = 0.50 if match.group("date") == "271014" else 0.67
    if header is not None:
        if len(header) != 6 or header[0] != original_id:
            raise ProtocolValidationError(f"source header does not match {filename}")
        if int(header[2]) != num_stacks or int(header[3]) != max_tiers:
            raise ProtocolValidationError(f"source dimensions do not match {filename}")
    ds1_id = f"ku2016-{original_id}"
    return BaseInstanceRef(
        base_instance_id=original_id,
        original_instance_id=original_id,
        ds1_instance_id=ds1_id,
        ds2_instance_id=f"{ds1_id}-merge2",
        parameter_group=_parameter_group(num_stacks, max_tiers, fill_rate),
    )


def discover_ku_base_instances(source_root: str | Path) -> Tuple[BaseInstanceRef, ...]:
    """Discover exact public Ku files without copying them into the manifest."""

    root = Path(source_root)
    if not root.is_dir():
        raise ProtocolValidationError(f"source root is not a directory: {root}")
    refs = []
    for path in sorted(root.rglob("*.txt")):
        try:
            first_line = path.read_text(encoding="utf-8").splitlines()[0].split()
        except (OSError, IndexError) as error:
            raise ProtocolValidationError(f"cannot read source header {path}: {error}") from error
        refs.append(_ref_from_source_filename(path.name, first_line))
    if not refs:
        raise ProtocolValidationError(f"no Ku source files found under {root}")
    if len({ref.base_instance_id for ref in refs}) != len(refs):
        raise ProtocolValidationError("duplicate original instance IDs discovered")
    return tuple(refs)


def build_split_manifest(
    refs: Iterable[BaseInstanceRef],
    *,
    split_seed: int,
    split_counts: SplitCounts = SplitCounts(),
    dataset_version: str = DEFAULT_DATASET_VERSION,
) -> SplitManifest:
    """Stratify by parameter group using deterministic hash ranking."""

    if isinstance(split_seed, bool) or not isinstance(split_seed, int):
        raise ProtocolValidationError("split_seed must be an integer")
    grouped: Dict[str, list[BaseInstanceRef]] = {}
    for ref in refs:
        grouped.setdefault(ref.parameter_group, []).append(ref)
    if not grouped:
        raise ProtocolValidationError("at least one base instance is required")

    assignments: Dict[str, Dict[str, Tuple[BaseInstanceRef, ...]]] = {}
    for group, group_refs in sorted(grouped.items()):
        if len(group_refs) != split_counts.total:
            raise ProtocolValidationError(
                f"group {group} contains {len(group_refs)} refs; expected {split_counts.total}"
            )
        ranked = sorted(
            group_refs,
            key=lambda ref: (
                hashlib.sha256(
                    f"{SPLIT_PROTOCOL_VERSION}|{split_seed}|{group}|{ref.base_instance_id}".encode()
                ).digest(),
                ref.base_instance_id,
            ),
        )
        train_end = split_counts.train
        validation_end = train_end + split_counts.validation
        assignments[group] = {
            "train": tuple(ranked[:train_end]),
            "validation": tuple(ranked[train_end:validation_end]),
            "test": tuple(ranked[validation_end:]),
        }
    return SplitManifest(
        protocol_version=SPLIT_PROTOCOL_VERSION,
        dataset_version=dataset_version,
        split_seed=split_seed,
        split_counts=split_counts,
        groups=assignments,
    )


def save_split_manifest(manifest: SplitManifest, path: str | Path) -> Path:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        json.dumps(manifest.to_record(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return destination


def load_split_manifest(path: str | Path) -> SplitManifest:
    source = Path(path)
    try:
        record = json.loads(source.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ProtocolValidationError(f"cannot read split manifest {source}: {error}") from error
    return SplitManifest.from_record(record)


class ScenarioSeedSchedule:
    """Disjoint, auditable seed streams indexed by base instance and visit."""

    SPLIT_BASE = {
        "train": 1_000_000_000_000,
        "validation": 2_000_000_000_000,
        "test": 3_000_000_000_000,
    }
    INSTANCE_STRIDE = 1_000_000

    def __init__(self, manifest: SplitManifest) -> None:
        self.manifest = manifest
        ordered_ids = sorted(ref.base_instance_id for ref in manifest.refs())
        self._rank = {base_id: rank for rank, base_id in enumerate(ordered_ids)}

    def seed_for(self, split: str, base_instance_id: str, scenario_index: int) -> int:
        if split not in SPLIT_NAMES:
            raise ProtocolValidationError(f"unknown split {split!r}")
        if self.manifest.split_for_base(base_instance_id) != split:
            raise ProtocolValidationError(
                f"base instance {base_instance_id} does not belong to {split}"
            )
        if (
            isinstance(scenario_index, bool)
            or not isinstance(scenario_index, int)
            or not 0 <= scenario_index < self.INSTANCE_STRIDE
        ):
            raise ProtocolValidationError(
                f"scenario_index must be in 0..{self.INSTANCE_STRIDE - 1}"
            )
        return (
            self.SPLIT_BASE[split]
            + self._rank[base_instance_id] * self.INSTANCE_STRIDE
            + scenario_index
        )

    def seeds(
        self, split: str, base_instance_id: str, count: int, *, start: int = 0
    ) -> Tuple[int, ...]:
        if isinstance(count, bool) or not isinstance(count, int) or count <= 0:
            raise ProtocolValidationError("scenario count must be a positive integer")
        return tuple(
            self.seed_for(split, base_instance_id, index)
            for index in range(start, start + count)
        )


@dataclass(frozen=True)
class ExperimentProtocolConfig:
    protocol_version: str = "scrp-formal-protocol-v1"
    dataset_version: str = DEFAULT_DATASET_VERSION
    split_manifest_version: str = SPLIT_PROTOCOL_VERSION
    observation_version: str = "O1"
    training_scenario_policy: str = "dynamic_per_base_instance_visit"
    training_dataset_strategy: str = "mixed_ds1_ds2_base_balanced"
    validation_scenarios_per_instance: int = 20
    development_scenarios_per_instance: int = 10
    formal_test_scenarios_per_instance: int = 50
    common_random_numbers: bool = True

    def __post_init__(self) -> None:
        if self.observation_version not in {"O1", "O2"}:
            raise ProtocolValidationError("observation_version must be O1 or O2")
        if not self.dataset_version or not self.protocol_version:
            raise ProtocolValidationError("protocol and dataset versions must be non-empty")
        counts = (
            self.validation_scenarios_per_instance,
            self.development_scenarios_per_instance,
            self.formal_test_scenarios_per_instance,
        )
        if any(isinstance(value, bool) or not isinstance(value, int) or value <= 0 for value in counts):
            raise ProtocolValidationError("scenario counts must be positive integers")
        if not self.common_random_numbers:
            raise ProtocolValidationError("formal protocol requires common random numbers")

    def to_record(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_record(cls, record: Mapping[str, Any]) -> "ExperimentProtocolConfig":
        if set(record) != set(cls().to_record()):
            raise ProtocolValidationError("protocol config keys mismatch")
        return cls(**record)


def save_protocol_config(config: ExperimentProtocolConfig, path: str | Path) -> Path:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        json.dumps(config.to_record(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return destination


def load_protocol_config(path: str | Path) -> ExperimentProtocolConfig:
    source = Path(path)
    try:
        record = json.loads(source.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ProtocolValidationError(f"cannot read protocol config {source}: {error}") from error
    return ExperimentProtocolConfig.from_record(record)


@dataclass(frozen=True)
class ScenarioResult:
    dataset: str
    split: str
    instance_id: str
    base_instance_id: str
    parameter_group: str
    scenario_seed: int
    scenario_id: str
    algorithm: str
    relocations: int
    terminated: bool
    truncated: bool

    def __post_init__(self) -> None:
        if self.dataset not in {"DS1", "DS2"}:
            raise ProtocolValidationError("dataset must be DS1 or DS2")
        if self.split not in SPLIT_NAMES:
            raise ProtocolValidationError(f"unknown split {self.split!r}")
        text_fields = (
            self.instance_id, self.base_instance_id, self.parameter_group,
            self.scenario_id, self.algorithm,
        )
        if any(not value for value in text_fields):
            raise ProtocolValidationError("scenario result identity fields must be non-empty")
        if isinstance(self.scenario_seed, bool) or not isinstance(self.scenario_seed, int):
            raise ProtocolValidationError("scenario_seed must be an integer")
        if isinstance(self.relocations, bool) or not isinstance(self.relocations, int) or self.relocations < 0:
            raise ProtocolValidationError("relocations must be a non-negative integer")
        if not isinstance(self.terminated, bool) or not isinstance(self.truncated, bool):
            raise ProtocolValidationError("terminated and truncated must be booleans")

    def to_record(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_record(cls, record: Mapping[str, Any]) -> "ScenarioResult":
        if set(record) != {field.name for field in fields(cls)}:
            raise ProtocolValidationError("scenario result keys mismatch")
        return cls(**record)
